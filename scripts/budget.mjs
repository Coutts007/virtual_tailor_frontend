#!/usr/bin/env node
/**
 * Bundle budgets (Section 18) from the production build's Vite manifest.
 * For each surface: gzip size of every JS chunk statically reachable from the
 * app entry, the root layout and the surface's routes (lazy chunks, workers and
 * models excluded). Also total CSS. Exits 1 on a breach. Run after npm run build.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const OUT = '.svelte-kit/output/client';
const manifest = JSON.parse(readFileSync(`${OUT}/.vite/manifest.json`, 'utf8'));
const NODES = '.svelte-kit/generated/client-optimized/nodes';
const BUDGET = { client: 120_000, dashboard: 200_000, css: 25_000 };

// node index → route file it renders
const nodeRoute = {};
for (const f of readdirSync(NODES)) {
	const src = readFileSync(`${NODES}/${f}`, 'utf8');
	const m = src.match(/src\/routes\/([^"']+)/);
	nodeRoute[`${NODES.replace(/^\.\//, '')}/${f}`] = m ? m[1] : '';
}

const gz = new Map();
const size = (file) => {
	if (!gz.has(file)) gz.set(file, gzipSync(readFileSync(`${OUT}/${file}`), { level: 9 }).length);
	return gz.get(file);
};

function closure(keys) {
	const seen = new Set();
	const files = new Set();
	const visit = (k) => {
		if (seen.has(k) || !manifest[k]) return;
		seen.add(k);
		files.add(manifest[k].file);
		for (const i of manifest[k].imports ?? []) visit(i);
	};
	keys.forEach(visit);
	return files;
}

const entry = Object.keys(manifest).filter(
	(k) => /client-optimized\/app\.js$/.test(k) || /entry\/start/.test(manifest[k].file)
);
const nodesOf = (re) =>
	Object.keys(manifest).filter((k) => k.includes('/nodes/') && re.test(nodeRoute[k] ?? ''));
const rootLayout = nodesOf(/^\+layout\.svelte$|^\+error\.svelte$/);
const clientLayout = nodesOf(/^\(client\)\/\+layout\.svelte$/);
const welcome = nodesOf(/^\(client\)\/\+page\.svelte$/);
const surfaces = {
	welcome: [...entry, ...rootLayout, ...clientLayout, ...welcome],
	client: [...entry, ...rootLayout, ...nodesOf(/^\(client\)/)],
	dashboard: [...entry, ...rootLayout, ...nodesOf(/^\(tailor\)|^\(auth\)/)],
	admin: [...entry, ...rootLayout, ...nodesOf(/^\(admin\)|^\(auth\)/)],
	study: [...entry, ...rootLayout, ...nodesOf(/^\(study\)|^\(auth\)/)]
};

const report = {};
for (const [name, keys] of Object.entries(surfaces)) {
	const files = [...closure(keys)];
	report[name] = files.reduce((s, f) => s + size(f), 0);
}
const cssFiles = readdirSync(`${OUT}/_app/immutable/assets`).filter((f) => f.endsWith('.css'));
report.cssFiles = cssFiles.reduce((s, f) => s + size(`_app/immutable/assets/${f}`), 0);
// Total CSS as one stream: what a client downloads over a compressed connection.
report.css = gzipSync(
	Buffer.concat(cssFiles.map((f) => readFileSync(`${OUT}/_app/immutable/assets/${f}`))),
	{ level: 9 }
).length;
// The client flow must not load dashboard code (Section 5).
const clientFiles = closure(surfaces.client);
const leaked = [...closure(nodesOf(/^\(tailor\)|^\(admin\)|^\(study\)/))].filter(
	(f) => clientFiles.has(f) && /nodes\//.test(f)
);

const kb = (n) => `${(n / 1000).toFixed(1)} KB`;
const rows = [
	['Client first load JS: Welcome (gzip)', report.welcome, BUDGET.client],
	['Tailor dashboard JS (gzip)', report.dashboard, BUDGET.dashboard],
	['Admin JS (gzip)', report.admin, BUDGET.dashboard],
	['Study JS (gzip)', report.study, BUDGET.dashboard],
	['CSS total (gzip, one stream)', report.css, BUDGET.css]
];
// Reported, not gated: every client page's code at once (pages load on demand).
const info = [
	['Client flow JS, all 17 pages together (gzip)', report.client],
	['CSS total (gzip, file by file)', report.cssFiles]
];
let ok = leaked.length === 0;
const lines = rows.map(([label, v, b]) => {
	const pass = v <= b;
	ok &&= pass;
	return `| ${label} | ${kb(v)} | ≤ ${kb(b)} | ${pass ? '✅' : '❌'} |`;
});
const md = `| Budget | Measured | Target | |\n|---|---|---|---|\n${lines.join('\n')}\n| Dashboard pages in the client bundle | ${leaked.length} | 0 | ${leaked.length ? '❌' : '✅'} |\n${info.map(([l, v]) => `| ${l} | ${kb(v)} | (info) | |`).join('\n')}\n`;
writeFileSync(
	'docs/budget-report.md',
	`# Bundle budget report\n\nGenerated by \`npm run budget\` after \`npm run build\` (Section 18). Workers, WASM and models are measured separately (see \`docs/device-test-log.md\`).\n\n${md}`
);
console.log(md);
if (!ok) process.exit(1);
