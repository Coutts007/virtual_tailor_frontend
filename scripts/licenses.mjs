#!/usr/bin/env node
/**
 * Generates docs/LICENSES.md from package-lock.json and fails (exit 1) if any
 * *deployed* (non-dev) dependency has a prohibited licence or is a prohibited
 * package (NFR-14, Section 2.3).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const ALLOWED =
	/^(MIT|ISC|0BSD|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|Unlicense|CC0-1\.0|BlueOak-1\.0\.0|Python-2\.0|MPL-2\.0|CC-BY-4\.0)$/;
const PROHIBITED_LICENCE = /(AGPL|GPL|LGPL|SSPL|BUSL|NC|non-?commercial|Commons-Clause)/i;
const PROHIBITED_NAME = /(ultralytics|yolo|smpl|bedlam|sapiens|bria|rembg)/i;

/** Model and WASM assets that are not npm packages; maintained by hand. */
const ASSETS = JSON.parse(readFileSync('scripts/assets-licences.json', 'utf8'));

const rows = [];
const problems = [];
for (const [path, meta] of Object.entries(lock.packages ?? {})) {
	if (!path) continue;
	const name = path.split('node_modules/').pop();
	let licence = meta.license;
	if (!licence) {
		const pj = join(path, 'package.json');
		if (existsSync(pj)) licence = JSON.parse(readFileSync(pj, 'utf8')).license;
	}
	licence = typeof licence === 'object' ? licence?.type : licence;
	licence ??= 'UNKNOWN';
	const deployed = !meta.dev && !meta.devOptional;
	rows.push({ name, version: meta.version, licence, deployed });
	if (!deployed) continue;
	const parts = String(licence)
		.replace(/[()]/g, '')
		.split(/\s+(?:OR|AND)\s+/);
	const ok = parts.some((p) => ALLOWED.test(p.trim()));
	if (PROHIBITED_NAME.test(name)) problems.push(`${name}: prohibited package`);
	else if (PROHIBITED_LICENCE.test(licence) && !ok)
		problems.push(`${name}@${meta.version}: prohibited licence ${licence}`);
	else if (!ok) problems.push(`${name}@${meta.version}: unreviewed licence ${licence}`);
}
for (const a of ASSETS) {
	if (
		PROHIBITED_NAME.test(a.name) ||
		(PROHIBITED_LICENCE.test(a.licence) && !ALLOWED.test(a.licence))
	)
		problems.push(`${a.name}: prohibited asset licence ${a.licence}`);
}

rows.sort((a, b) => Number(b.deployed) - Number(a.deployed) || a.name.localeCompare(b.name));
const table = (list) =>
	[
		'| Package | Version | Licence |',
		'|---|---|---|',
		...list.map((r) => `| ${r.name} | ${r.version} | ${r.licence} |`)
	].join('\n');

const md = `# Licence inventory (NFR-14)

Generated by \`npm run licenses\` from \`package-lock.json\`. Do not edit by hand.

**Never deploy:** Ultralytics YOLO (AGPL-3.0), SMPL/SMPL-X or BEDLAM-derived weights (non-commercial), Sapiens (CC BY-NC), rembg's default \`bria-rmbg\` model (commercial licence).

## Deployed dependencies (shipped to users)

${table(rows.filter((r) => r.deployed))}

## Models, WASM and other bundled assets

| Asset | Source | Licence |
|---|---|---|
${ASSETS.length ? ASSETS.map((a) => `| ${a.name} | ${a.source} | ${a.licence} |`).join('\n') : '| (none yet; models arrive in Phase 3) | | |'}

## Development-only dependencies (not shipped)

${rows.filter((r) => !r.deployed).length} packages. Licences:
${Object.entries(
	rows
		.filter((r) => !r.deployed)
		.reduce((m, r) => ((m[r.licence] = (m[r.licence] ?? 0) + 1), m), {})
)
	.sort((a, b) => b[1] - a[1])
	.map(([l, n]) => `- ${l}: ${n}`)
	.join('\n')}

## Check result

${problems.length ? problems.map((p) => `- ❌ ${p}`).join('\n') : '✅ No prohibited or unreviewed licences in deployed dependencies.'}
`;
writeFileSync('docs/LICENSES.md', md);
if (problems.length) {
	console.error(problems.join('\n'));
	process.exit(1);
}
console.log(
	`docs/LICENSES.md written: ${rows.filter((r) => r.deployed).length} deployed, ${rows.length} total.`
);
